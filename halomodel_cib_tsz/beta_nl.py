"""
Non linear halo bias beta^NL, from Mead and Verde (2021), as adopted by
Jego et al. (2026).

Provenance: copied from the ksz_co pipeline
(halo_model-master/software/halo_model/halo_model/beta_nl.py, 2026-10) with
only the table lookup changed to point at this package's data directory
(data/beta_nl/bnl_tables.npz, byte identical to ksz_co betanl/data). The
class itself is unchanged so that the two pipelines evaluate the same beta.
In this package it is used through HaloModel(beta_nl=True), which applies
beta_med(k, z) ("med" mode) at every two halo site:
P_2h(k, z) = P_lin(k, z) [1 + beta_med(k, z)]. See docs/decisions.md.

The two halo term of every component currently assumes

    P_hh(k, z, M, M') = b(z,M) b(z,M') P_lin(k, z)

and this module supplies the correction that turns that into

    P_hh(k, z, M, M') = b(z,M) b(z,M') P_lin(k, z) [1 + beta^NL(k, z, M, M')]

Nothing here knows about the halo model. It loads the calibration tables, deals
with units, interpolation and every kind of extension outside the calibrated
box, and hands back either beta itself or the projection machinery that
halo_model.py contracts against its own mass weights.

Conventions, and where each one comes from
------------------------------------------
* **Lookup in peak height, not mass.** Mead's own reader (`init_BNL` in
  hmx.f90) builds a 3D interpolator in `(k, nu1, nu2)` and evaluates it as
  `BNL(k, nu1, nu2, ...)`. The `nu` column of the `_binstats.dat` files exists
  for exactly this. It is also the right choice for us: nu absorbs both the
  cosmology difference against MultiDark and the fact that our CIB halos are
  Delta = 200 and our tSZ halos Delta = 500, since our own sigma(M,z) is shared
  between the two and only the mass function and bias carry the Delta.
  `lookup="logm"` interpolates in log10 mass instead, which is how the Jego
  paper describes it, and is kept as a systematics variant.

* **Units.** Table wavenumbers are h/Mpc and table masses are Msun/h, both with
  MultiDark's h = 0.70. Our k is Mpc^-1 and our masses are Msun. In the nu
  lookup no mass conversion happens at all, so k is the only h factor that can
  bite, and `k_h_convention` decides it. "target" divides by our h, "multidark"
  divides by 0.70; those differ from each other by four percent and both follow
  the standard reading, that the stored number X means k = X h Mpc^-1.
  **"paper" multiplies instead, and is now known to be WRONG. Do not use it and
  do not quote it as a systematic.** Baptiste Jego confirmed on 2026-09-22 that
  their main code saves k in h/Mpc and addresses physical k in Mpc^-1 by putting
  h to its value, i.e. it divides by h exactly as "target" does, and that the
  figure axes are generated by a separate script and are probably wrong. The
  option is kept only so the old comparison can be reproduced.

  What made it look right: Jego et al.'s published figures imply the inverted
  reading. The last point of their Fig. 1 sits at k = 1.055 Mpc^-1, which is
  the last tabulated k of 0.7383 divided by 0.70, and their grey region ends at
  0.115 Mpc^-1, which is their stated 0.08 h/Mpc divided by 0.70; their mass
  axis is inverted the same way, and it is the only setting that reproduces
  their Fig. A.1. It places the lookup a factor h^2 lower in k, which roughly
  halves beta. All of that is now understood as a figure bug.

* **k.** beta is zero below `kmin_hmpc` = 0.08 h/Mpc, where the measurements
  are consistent with zero. Between there and the last tabulated k it is
  interpolated linearly in log k. Above, `k_extrap` chooses: "powerlaw" is what
  the paper does, per redshift and per mass pair, capped at
  `kmax_extrap_hmpc` = 10 and frozen above that; "freeze" holds the last
  tabulated value, which is what Mead's own code does (it clamps k to the table
  maximum before evaluating); "zero" switches the correction off there.
  Our multipoles reach k far beyond the table, so this choice matters much more
  for us than it did for the paper. See the module test for the numbers.

* **Redshift.** Tables run z = 0 to 2.89 and are interpolated linearly in z
  between snapshots. Above 2.89 `z_extrap` chooses, and the default is
  **"plateau"**, holding beta fixed at its z = 2.89 value *at fixed peak
  height*. That is not laziness, it is what the tables support. Over the narrow
  nu range every snapshot above z = 1 covers without clamping, nu 2.37 to 2.61,
  beta at fixed nu scatters by 36 to 65 percent across z with no clean trend,
  so a fitted slope there is fitting noise. The real redshift dependence is
  not in beta at fixed nu, it is in nu itself: at fixed halo MASS beta rises
  monotonically, 1.22 to 4.65 between z = 1 and z = 2.89 at the largest
  tabulated k, and our lookup gets that for free through nu(M,z). "logslope"
  and "sigmoid" continue a fitted slope and are kept for the Phase 5
  systematics, with `z_slope_var` choosing whether the fit is linear in z,
  which is what Jego et al.'s Fig. A.1 extension is, or in ln(1+z).

  All schemes are frozen above `z_extrap_max` = 7, the paper's ceiling; our z
  grid runs to 10.2, and freezing costs nothing because below one part in a
  thousand of any two halo term comes from z > 7.

* **Outside the calibrated mass range.** Held constant at the nearest reliable
  value, at both ends, as the paper does. "Reliable" is decided by the upstream
  error tables rather than by a mass or rarity threshold, because neither of
  those expresses it: the same mass is common at z = 0 and nearly absent at
  z = 3, while at fixed nu the number of halos in a fixed box still moves with
  redshift. `bin_err_max` (default 0.1) keeps only the mass bins whose quoted
  error on 1 + beta, maximised over the k range actually used, is below that.
  That keeps three or four bins at every snapshot and leaves beta at the last
  tabulated k in [0.22, 4.65] across all of them; admitting the next bin lets
  in values up to 8.8 with slopes up to 21, and the rarest corner of the raw
  tables reaches 1 + beta of order 800. `nu_max_reliable` and
  `logm_max_reliable` are available as an additional cut and are off by
  default.

The calibration was performed in MultiDark (Om = 0.27, h = 0.70, sigma8 = 0.82)
and is applied here to a different cosmology without the AW10 rescaling that
Mead's code offers. The paper does the same. Recorded, not corrected.
"""

import os

import numpy as np

H_MULTIDARK = 0.70          # MultiDark MDR1
DELTA_C = 1.686             # matches halo_model.py's bias(), which fixes it

_HERE = os.path.dirname(os.path.abspath(__file__))


def default_table_file(modules_data=None):
    """Where to look for the parsed tables.

    `modules_data`, if given, is a directory searched first for
    beta_nl/bnl_tables.npz; the copy shipped in this package's data
    directory is the fallback.
    """
    candidates = []
    if modules_data:
        candidates.append(os.path.join(modules_data, "beta_nl",
                                       "bnl_tables.npz"))
    candidates.append(os.path.join(_HERE, "data", "beta_nl", "bnl_tables.npz"))
    for c in candidates:
        if os.path.isfile(c):
            return c
    raise FileNotFoundError(
        "beta^NL tables not found. Looked in:\n  " + "\n  ".join(candidates))


def _interp_weights(x, nodes, clamp_lo=None, clamp_hi=None):
    """Linear interpolation weights of `x` on `nodes`, as a sparse-in-spirit
    dense matrix of shape x.shape + (len(nodes),), each row summing to one.

    Values outside [clamp_lo, clamp_hi] are first clamped to that window, which
    is how "held constant at the nearest reliable value" is implemented: the
    weight lands entirely on the boundary node (or is shared between the two
    nodes bracketing the boundary, which is the same thing done smoothly).
    `nodes` must be increasing.
    """
    x = np.asarray(x, dtype=float)
    lo = nodes[0] if clamp_lo is None else max(nodes[0], clamp_lo)
    hi = nodes[-1] if clamp_hi is None else min(nodes[-1], clamp_hi)
    if hi <= lo:
        raise ValueError(f"empty reliable window: [{lo}, {hi}]")
    xc = np.clip(x, lo, hi)

    i = np.clip(np.searchsorted(nodes, xc, side="right") - 1, 0, len(nodes) - 2)
    x0, x1 = nodes[i], nodes[i + 1]
    t = (xc - x0) / (x1 - x0)

    W = np.zeros(xc.shape + (len(nodes),))
    idx = np.indices(xc.shape)
    W[(*idx, i)] = 1.0 - t
    W[(*idx, i + 1)] = t
    return W


class BetaNL:
    """Tabulated beta^NL with all the out of box extensions applied."""

    def __init__(self, table_file=None, h=None, *,
                 modules_data=None,
                 lookup="nu",
                 beta_mode="full",
                 med_logm_range=(11.5, 14.5),
                 k_h_convention="target",
                 kmin_hmpc=0.08,
                 k_extrap="powerlaw",
                 kmax_extrap_hmpc=10.0,
                 kslope_npts=None,
                 slope_clip=(-2.0, 1.5),
                 nu_zero_above=None,
                 z_extrap="plateau",
                 z_extrap_max=7.0,
                 z_slope_ref=1.8,
                 z_slope_var="z",
                 bin_err_max=0.1,
                 nu_min_reliable=None,
                 nu_max_reliable=None,
                 logm_min_reliable=None,
                 logm_max_reliable=None,
                 amplitude=1.0):
        if lookup not in ("nu", "logm"):
            raise ValueError(f"lookup must be 'nu' or 'logm', got {lookup!r}")
        if k_h_convention not in ("target", "multidark", "paper"):
            raise ValueError("k_h_convention must be 'target', 'multidark' or "
                             "'paper'")
        if k_extrap not in ("powerlaw", "freeze", "zero"):
            raise ValueError("k_extrap must be 'powerlaw', 'freeze' or 'zero'")
        if z_extrap not in ("logslope", "plateau", "sigmoid"):
            raise ValueError("z_extrap must be 'logslope', 'plateau' or "
                             "'sigmoid'")
        if h is None:
            raise ValueError("h is required: it sets the k unit conversion")

        self.table_file = table_file or default_table_file(modules_data)
        d = np.load(self.table_file, allow_pickle=False)
        self.z = d["z"]                       # (ns,), ascending
        self.k_hmpc = d["k_hmpc"]             # (nk,)
        self.beta = d["beta"]                 # (ns, nk, nbin, nbin)
        self.nu_cen = d["nu_cen"]             # (ns, nbin)
        self.logm_cen = d["logm_cen"]         # (ns, nbin), log10(Msun/h)
        self.beta_err = d["beta_err"] if "beta_err" in d.files else None
        self.h_multidark = float(d["h_multidark"])
        self.table_set = str(d["table_set"])
        self.source_sha = str(d["source_sha"])

        if beta_mode not in ("full", "med"):
            raise ValueError("beta_mode must be 'full' or 'med'")
        if beta_mode == "med":
            # Jego et al.'s simplified prescription: replace beta at each
            # (k, z) by its median over mass pairs in the well sampled range
            # they quote, 10^11.5 to 10^14.5 Msun, and use that one value for
            # every pair. It is mass independent by construction, so the mass
            # weighting drops out entirely and the effective beta the halo
            # model applies IS this number.
            logm = self.logm_cen - np.log10(self.h_multidark)
            med = np.empty_like(self.beta)
            for i in range(self.beta.shape[0]):
                sel = ((logm[i] >= med_logm_range[0])
                       & (logm[i] <= med_logm_range[1]))
                if sel.sum() == 0:
                    raise ValueError(f"no mass bins in {med_logm_range} at "
                                     f"z = {self.z[i]}")
                iu = np.triu_indices(int(sel.sum()))
                for j in range(self.beta.shape[1]):
                    g = self.beta[i, j][np.ix_(sel, sel)]
                    med[i, j] = np.median(g[iu])
            self.beta = med
        self.beta_mode = beta_mode
        self.med_logm_range = tuple(med_logm_range)

        self.h = float(h)
        self.lookup = lookup
        self.k_h_convention = k_h_convention
        # "target" and "multidark" both divide by h, which is the standard
        # reading of "k in h/Mpc": the stored number X means k = X h Mpc^-1, so
        # X = k[Mpc^-1] / h, confirmed by the author 2026-09-22 to be what
        # their code does. "paper" multiplies instead, which is what Jego et
        # al.'s published figures imply and is the only way to reproduce their
        # Fig. A.1. See betanl/validate_against_paper.py.
        self.k_h_exponent = 1.0 if k_h_convention == "paper" else -1.0
        self.h_k = self.h if k_h_convention == "target" else self.h_multidark
        self.kmin_hmpc = float(kmin_hmpc)
        self.k_extrap = k_extrap
        self.kmax_extrap_hmpc = float(kmax_extrap_hmpc)
        self.slope_clip = tuple(slope_clip)
        self.z_extrap = z_extrap
        self.z_extrap_max = float(z_extrap_max)
        self.amplitude = float(amplitude)
        # Mead's own evaluator sets BNL = 0 whenever either halo has
        # nu > numax_bnl (10 by default in hmx.f90). `nu_zero_above` is that
        # switch with a lower threshold: pairs involving a halo above it get
        # no correction at all, instead of the clamped value of the last
        # reliable bin. It exists for the tSZ leg, whose weight sits at
        # nu 3 to 4 where the tables are noise.
        if nu_zero_above is not None and lookup != "nu":
            raise ValueError("nu_zero_above needs lookup='nu'")
        self.nu_zero_above = None if nu_zero_above is None else float(nu_zero_above)

        if lookup == "nu":
            self.nodes = self.nu_cen
            self.lo = nu_min_reliable
            self.hi = nu_max_reliable
        else:
            # tables are Msun/h, our masses are Msun: this is the one place a
            # mass h factor appears, and the test pins it
            self.nodes = self.logm_cen - np.log10(self.h_multidark)
            self.lo = logm_min_reliable
            self.hi = logm_max_reliable

        # snapshots used for the high redshift slope fit, ordered with the
        # last snapshot first so that slot 0 is always the boundary value
        fit = np.flatnonzero(self.z >= float(z_slope_ref))
        if len(fit) < 2:
            fit = np.arange(len(self.z) - 2, len(self.z))
        fit = fit[::-1]
        self.z_slope_ref = float(z_slope_ref)
        self._fit_idx = fit
        self._nslots = max(2, len(fit))
        if len(fit) < self._nslots:                       # pad, zero weighted
            self._fit_idx = np.concatenate(
                [fit, np.full(self._nslots - len(fit), fit[0])])
        if z_slope_var not in ("z", "log1pz"):
            raise ValueError("z_slope_var must be 'z' or 'log1pz'")
        self.z_slope_var = z_slope_var
        # Jego et al.'s "local slope" curve is linear in z, not in ln(1+z):
        # digitising their Fig. A.1 beyond z = 2.89 gives 1.39, 1.69, 2.06,
        # 2.66, 3.33 at z = 3.0, 3.5, 4.0, 5.0, 6.0, which is a straight line
        # in z to better than 0.03. "z" reproduces that; "log1pz" is the
        # variant this module used before that was measured.
        L = (self.z[self._fit_idx] if z_slope_var == "z"
             else np.log1p(self.z[self._fit_idx]))
        self._L_fit = L
        dev = L - L.mean()
        self._slope_w = dev / np.sum(dev ** 2)

        # which mass bins to trust, per snapshot
        nb = self.beta.shape[2]
        keep = np.ones((len(self.z), nb), dtype=bool)
        if bin_err_max is not None and beta_mode == "med":
            bin_err_max = None      # every bin holds the same number
        if bin_err_max is not None:
            if self.beta_err is None:
                raise ValueError(
                    "bin_err_max needs the upstream error tables; rebuild the "
                    "npz with betanl/fetch_bnl_tables.py, or pass "
                    "bin_err_max=None")
            used = self.k_hmpc >= self.kmin_hmpc
            diag = np.einsum("zkbb->zkb", self.beta_err[:, used])
            keep &= diag.max(axis=1) < float(bin_err_max)
        if self.lo is not None:
            keep &= self.nodes >= self.lo
        if self.hi is not None:
            keep &= self.nodes <= self.hi
        if keep.sum(axis=1).min() < 1:
            raise ValueError("the reliability cut left a snapshot with no "
                             "usable mass bins")
        self.bin_err_max = bin_err_max
        self._keep = keep

        # power law slope in k at the last tabulated point, per snapshot and
        # mass pair. The paper fits it from the tabulated points; with two
        # points that is the log ratio of the last two, which for beta_med is
        # noisy enough to change sign between neighbouring snapshots (at
        # z = 2.15 the median at the last k is below the one before it). So
        # the fit runs over the last `kslope_npts` points, least squares in
        # log beta against log k, using only positive values. Default: 2 in
        # full mode, which keeps the earlier behaviour and tests, 4 in med.
        if kslope_npts is None:
            kslope_npts = 4 if beta_mode == "med" else 2
        self.kslope_npts = int(kslope_npts)
        if self.kslope_npts < 2:
            raise ValueError("kslope_npts must be at least 2")
        bt = self.beta[:, -self.kslope_npts:]                 # (ns, n, nb, nb)
        lk = np.log(self.k_hmpc[-self.kslope_npts:])
        pos = bt > 0
        with np.errstate(divide="ignore", invalid="ignore"):
            lb = np.where(pos, np.log(np.where(pos, bt, 1.0)), 0.0)
        n = pos.sum(axis=1)                                   # (ns, nb, nb)
        lkb = lk[None, :, None, None] * np.ones_like(bt)
        sx = np.where(pos, lkb, 0.0).sum(axis=1)
        sy = lb.sum(axis=1)
        sxx = np.where(pos, lkb ** 2, 0.0).sum(axis=1)
        sxy = (np.where(pos, lkb, 0.0) * lb).sum(axis=1)
        with np.errstate(divide="ignore", invalid="ignore"):
            p = (n * sxy - sx * sy) / (n * sxx - sx ** 2)
        p = np.where((n >= 2) & np.isfinite(p), p, 0.0)
        self._kslope = np.clip(p, *self.slope_clip)

    # -- description ------------------------------------------------------
    def describe(self):
        return (f"beta^NL set {self.table_set} @ {self.source_sha[:8]}, "
                f"{len(self.z)} snapshots z {self.z[0]:.2f}-{self.z[-1]:.2f}, "
                f"{self.beta.shape[2]} {self.lookup} bins, "
                f"k {self.k_hmpc[0]:.4g}-{self.k_hmpc[-1]:.4g} h/Mpc\n"
                f"  lookup={self.lookup} k_h={self.k_h_convention} "
                f"(h={self.h_k:.4f}) k_extrap={self.k_extrap} "
                f"z_extrap={self.z_extrap} (max {self.z_extrap_max}, "
                f"slope fit over z >= {self.z_slope_ref}, "
                f"{len(self._fit_idx)} snapshots) "
                f"beta_mode={self.beta_mode} kslope_npts={self.kslope_npts} "
                f"nu_zero_above={self.nu_zero_above} "
                f"bin_err_max={self.bin_err_max} "
                f"(bins kept per snapshot "
                f"{self._keep.sum(axis=1).min()}-{self._keep.sum(axis=1).max()}"
                f"), extra {self.lookup} window [{self.lo}, {self.hi}], "
                f"amplitude={self.amplitude}")

    # -- k -----------------------------------------------------------------
    def k_to_hmpc(self, k_mpc):
        """Our Mpc^-1 wavenumbers as a table index.

        Standard: the table stores X with k = X h Mpc^-1, so X = k / h.
        k_h_convention="paper" instead returns k * h, which is what the
        published figures of Jego et al. imply; it places the lookup a factor
        h^2 = 0.45 lower in k and roughly halves beta.
        """
        return np.asarray(k_mpc, dtype=float) * self.h_k ** self.k_h_exponent

    def beta_at_k(self, k_hmpc, isnap):
        """beta for snapshot(s) `isnap` at arbitrary k, shape
        broadcast(k, isnap) + (nbin, nbin).

        Linear in log k inside the table, then k_extrap outside, then zero
        below kmin_hmpc.
        """
        k_hmpc = np.asarray(k_hmpc, dtype=float)
        isnap = np.asarray(isnap)
        kt = self.k_hmpc
        kmax = kt[-1]

        keff = np.minimum(k_hmpc, self.kmax_extrap_hmpc)  # freeze above the cap
        kin = np.minimum(keff, kmax)

        lw = _interp_weights(np.log(kin), np.log(kt))      # (..., nk)
        b = self.beta[isnap]                               # (..., nk, nb, nb)
        out = np.einsum("...k,...kij->...ij", lw, b)

        above = keff > kmax
        if np.any(above):
            if self.k_extrap == "zero":
                out = np.where(above[..., None, None], 0.0, out)
            elif self.k_extrap == "powerlaw":
                ratio = np.where(above, keff / kmax, 1.0)
                fac = ratio[..., None, None] ** self._kslope[isnap]
                out = np.where(above[..., None, None], out * fac, out)
            # "freeze" needs nothing: kin already clamped to kmax

        out = np.where((k_hmpc < self.kmin_hmpc)[..., None, None], 0.0, out)
        return self.amplitude * out

    # -- z ------------------------------------------------------------------
    def z_slots(self, z):
        """For each z, which snapshots to combine and with what weights.

        Returns (snap_index[..., S], weight[..., S], extrap[...], remap).

        Inside the tabulated range this is ordinary linear interpolation and
        only two slots are non zero. Above it, all three schemes are linear
        functionals of the tabulated values, so they are expressed as weights
        too, with slot 0 carrying the last snapshot so that "the value at the
        boundary" is always `v[0]`.

        The slope is a least squares fit in `z_slope_var` over every snapshot
        above `z_slope_ref`, not a two point difference: the last two snapshots
        are 0.41 apart in z while the extension to z = 7 spans 4.1, so a two
        point slope gets multiplied by ten and is dominated by whichever way
        the last snapshot happened to scatter.

        The "sigmoid" scheme is not a linear functional, so it is applied
        afterwards by `_z_combine`, to the value the weights produce. It
        therefore saturates the *effective* beta of a given (ell, z) rather
        than each (M, M') element separately. That is deliberate: the
        alternative is to re express every slot on one snapshot's node grid
        first, and since the node grids move fast with redshift near the top of
        the table, that regridding changed the extrapolated slope by more than
        the sigmoid itself does. As a systematics variant, saturating the
        effective beta is the honest version of "what if the high redshift
        growth flattens", and it keeps the pointwise evaluator and the
        contraction exactly consistent.
        """
        z = np.asarray(z, dtype=float)
        zt = self.z
        nz = len(zt)
        S = self._nslots

        i = np.clip(np.searchsorted(zt, z, side="right") - 1, 0, nz - 2)
        t = (z - zt[i]) / (zt[i + 1] - zt[i])

        idx = np.zeros(z.shape + (S,), dtype=int)
        w = np.zeros(z.shape + (S,))
        idx[..., 0] = i
        idx[..., 1] = i + 1
        idx[..., 2:] = nz - 1
        w[..., 0] = 1.0 - t
        w[..., 1] = t

        extrap = z > zt[-1]
        if np.any(extrap):
            zc = np.minimum(z, self.z_extrap_max)
            L = zc if self.z_slope_var == "z" else np.log1p(zc)
            we = self._extrap_weights(L)                    # (..., S)
            idx = np.where(extrap[..., None], self._fit_idx, idx)
            w = np.where(extrap[..., None], we, w)

        return idx, w, extrap

    def _extrap_weights(self, L):
        """Weights on `self._fit_idx` giving value(L_last) + slope * (L-L_last),
        with the slope least squares fitted over the fit snapshots. For the
        plateau scheme the slope term is dropped."""
        S = self._nslots
        out = np.zeros(np.shape(L) + (S,))
        out[..., 0] = 1.0                                   # the boundary value
        if self.z_extrap == "plateau":
            return out
        dL = np.asarray(L)[..., None] - self._L_fit[0]      # slot 0 is the last
        return out + dL * self._slope_w

    def _z_combine(self, v, w, extrap):
        """Combine the slots. `v` is (S, ...) and `w` is (..., S).

        The sigmoid scheme takes the fitted increment and passes it through a
        tanh that saturates at the magnitude of the boundary value, so value
        and initial slope both match the last tabulated snapshot.
        """
        lin = np.einsum("s...,...s->...", v, w)
        if self.z_extrap != "sigmoid" or not np.any(extrap):
            return lin
        base = v[0]
        amp = np.abs(base)
        safe = np.where(amp > 0, amp, 1.0)
        sig = np.where(amp > 0, base + amp * np.tanh((lin - base) / safe), base)
        return np.where(extrap, sig, lin)

    # -- the general evaluator, used by the tests and the plots -------------
    def beta_of(self, k_mpc, z, x1, x2):
        """beta at matching arrays of k [Mpc^-1], z, and two lookup
        coordinates (nu, or log10 M in Msun when lookup="logm")."""
        k_mpc, z, x1, x2 = np.broadcast_arrays(
            *(np.asarray(a, dtype=float) for a in (k_mpc, z, x1, x2)))
        kh = self.k_to_hmpc(k_mpc)
        idx, w, extrap = self.z_slots(z)

        vals = []
        for s in range(self._nslots):
            isn = idx[..., s]
            bk = self.beta_at_k(kh, isn)                       # (..., nb, nb)
            w1 = self._node_weights(x1, isn)
            w2 = self._node_weights(x2, isn)
            vals.append(np.einsum("...i,...ij,...j->...", w1, bk, w2))
        return self._z_combine(np.array(vals), w, extrap)

    def _node_weights(self, x, isnap):
        """Lookup weights on each snapshot's own node grid, shape
        x.shape + (nbin,), zero on the bins the reliability cut dropped.

        The node grid moves with redshift, so this cannot be hoisted out of the
        snapshot loop. Clamping to the ends of the retained node list is what
        "held constant at the nearest reliable value" means.
        """
        x = np.asarray(x, dtype=float)
        isnap = np.broadcast_to(np.asarray(isnap), x.shape)
        nb = self.beta.shape[2]
        W = np.zeros(x.shape + (nb,))
        for s in np.unique(isnap):
            m = isnap == s
            cols = np.flatnonzero(self._keep[s])
            Wm = np.zeros(x[m].shape + (nb,))
            if len(cols) == 1:
                Wm[..., cols[0]] = 1.0
            else:
                Wm[..., cols] = _interp_weights(x[m], self.nodes[s][cols])
            W[m] = Wm
        if self.nu_zero_above is not None:
            # a zero weight row makes beta vanish for every pair involving
            # that halo, which is what Mead's numax_bnl does
            W[x > self.nu_zero_above] = 0.0
        return W

    # -- the mass independent prescription -----------------------------------
    def beta_kz(self, k_mpc, z):
        """beta_med at matching arrays of k [Mpc^-1] and z, med mode only.

        In med mode every mass pair holds the same number, so the mass lookup
        is a formality: any weights summing to one return it. This is the
        whole of what halo_model.py needs in that mode, one (ell, z) array,
        and the projector, the per component contraction and beta_eff are
        not involved.
        """
        if self.beta_mode != "med":
            raise ValueError("beta_kz is defined for beta_mode='med' only")
        if self.nu_zero_above is not None:
            raise ValueError("nu_zero_above has no meaning in med mode")
        k_mpc, z = np.broadcast_arrays(np.asarray(k_mpc, float),
                                       np.asarray(z, float))
        x = np.full(k_mpc.shape, self.nodes[0][0])
        return self.beta_of(k_mpc, z, x, x)

    # -- what halo_model.py contracts against -------------------------------
    def projector(self, x_mz, z, k_lz):
        """Precompute everything that does not depend on the sampled
        parameters, for the per component contraction in Phase 2.

        Inputs
            x_mz : (nm, nz) lookup coordinate of our mass grid, nu or log10 M
            z    : (nz,)
            k_lz : (nl, nz) wavenumbers in Mpc^-1, that is ell / chi(z)

        Returns a dict with
            W  : (nz, 2, nm, nbin) mass to node weights per snapshot slot
            B  : (nl, nz, 2, nbin, nbin) beta at k(l,z) for that slot
            wz : (nz, 2) redshift combination weights
            extrap : (nz,) bool, where the redshift extension is active

        `contract` then turns mass weights into the *exact* double mass
        integral of A B beta, not an approximation to it: bilinear
        interpolation of beta on the node grid factorises into two independent
        one dimensional projections.
        """
        x_mz = np.asarray(x_mz, dtype=float)
        z = np.asarray(z, dtype=float)
        k_lz = np.asarray(k_lz, dtype=float)
        nm, nz = x_mz.shape
        nl = k_lz.shape[0]
        nb = self.beta.shape[2]

        idx, wz, extrap = self.z_slots(z)
        kh = self.k_to_hmpc(k_lz)                          # (nl, nz)
        S = self._nslots
        # Only the bins the reliability cut kept ever carry weight, so both
        # arrays are built in that reduced basis. It is three or four bins
        # rather than eight, which makes the contraction downstream four times
        # cheaper for an identical answer.
        nbe = int(self._keep.sum(axis=1).max())

        W = np.zeros((nz, S, nm, nbe))
        B = np.zeros((nl, nz, S, nbe, nbe))
        for iz in range(nz):
            for s in range(S):
                isn = int(idx[iz, s])
                cols = np.flatnonzero(self._keep[isn])
                n = len(cols)
                B[:, iz, s, :n, :n] = self.beta_at_k(kh[:, iz], isn)[
                    :, cols[:, None], cols[None, :]]
                W[iz, s, :, :n] = self._node_weights(
                    x_mz[:, iz], isn)[:, cols]
        return dict(W=W, B=B, wz=wz, extrap=extrap, idx=idx)

    def project(self, proj, A):
        """Project one mass kernel A(l, m, z), quadrature weights included,
        onto the node basis: (nl, nz, S, nbin).

        Every two halo leg in the halo model is a linear combination of a
        handful of these, with coefficients that depend on frequency and
        redshift but not on halo mass, so projecting the basis once and
        combining afterwards is far cheaper than projecting each leg.
        """
        return np.einsum("lmz,zsmb->lzsb", A, proj["W"], optimize=True)

    def contract_projected(self, proj, a, c):
        """The exact double mass integral of A C beta, from two projections."""
        num = np.einsum("lzsb,lzsbc,lzsc->slz", a, proj["B"], c, optimize=True)
        # wz is (nz, S) and num[s] is (nl, nz): both broadcast from the right
        return self._z_combine(num, proj["wz"], proj["extrap"])

    def contract_many(self, proj, lefts, rights):
        """`contract_projected` for a stack of leg pairs at once.

        lefts and rights are (npair, nl, nz, S, nbin). One einsum over the
        whole stack rather than one per pair: the per pair arrays are small
        enough that einsum's own overhead was four fifths of the cost.
        """
        num = np.einsum("plzsb,lzsbc,plzsc->splz", lefts, proj["B"], rights,
                        optimize=True)
        return self._z_combine(num, proj["wz"], proj["extrap"])

    def contract(self, proj, A, C):
        """The exact double mass integral of A(l,m,z) C(l,m,z) beta, given
        weights that already carry their quadrature factors."""
        return self.contract_projected(proj, self.project(proj, A),
                                       self.project(proj, C))
